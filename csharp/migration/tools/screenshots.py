#!/usr/bin/env python3
"""Builds SCREENSHOTS.md, the gallery of finished UI tickets, from screenshots.json (ticket -> scenario -> golden PNGs).
The PNGs are the committed goldens under Unciv.Godot.Harness/golden/, linked in place (nothing is copied).

  python3 -I tools/screenshots.py            rewrite SCREENSHOTS.md
  python3 -I tools/screenshots.py --check    exit 1 when SCREENSHOTS.md is stale, a golden is missing, or a Done C-track
                                             ticket has no entry in screenshots.json
  python3 -I tools/screenshots.py --missing  list Done C-track tickets without an entry

Entry: {"C017": {"scenario": "city-a", "about": "...", "shots": [{"golden": "city-a/open.png", "caption": "..."}]}}
or {"C007": {"none": "why there is no screenshot"}}.
An entry may instead carry documentation images, for what a golden cannot show (a real-GPU look): shots with
{"doc": "ultra/x.png"} are files under design/images/ (never goldens, never read by the scenario runner or CI comparisons);
such an entry has no "scenario" and a "doc_note" line saying where the images come from (see design/images/<dir>/README.md).
"""
import importlib.util
import json
import os
import sys
from pathlib import Path

HERE = Path(os.environ.get("TICKET_MIGRATION_DIR") or Path(__file__).resolve().parent.parent)
MAPPING = HERE / "screenshots.json"
OUTPUT = HERE / "SCREENSHOTS.md"
GOLDEN = HERE.parent / "Unciv.Godot.Harness" / "golden"
GOLDEN_REL = "../Unciv.Godot.Harness/golden"
DOC_IMAGES = HERE / "design" / "images"
DOC_REL = "design/images"


def load_ticket_tool():
    spec = importlib.util.spec_from_file_location("ticket_tool", Path(__file__).resolve().parent / "ticket.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def done_c_tickets(tool):
    return [(i, t) for i, t, s, _, _ in tool.tickets() if i.startswith("C") and s == "Done"]


def render(mapping, titles, golden_dir=GOLDEN, doc_dir=DOC_IMAGES):
    """Return (markdown, errors)."""
    errors = []
    out = [HEADER]
    none = []
    for tid in sorted(mapping):
        e = mapping[tid]
        title = titles.get(tid, "(ticket not Done or unknown)")
        if "none" in e:
            none.append((tid, title, e["none"]))
            continue
        intro = f"Scenario `{e['scenario']}`.\n" if "scenario" in e else ""
        if "doc_note" in e:
            intro += f"\n{e['doc_note']}\n"
        out.append(f"## {tid} {title}\n\n{e['about']}\n\n{intro}")
        for s in e["shots"]:
            if "doc" in s:
                if not (doc_dir / s["doc"]).is_file():
                    errors.append(f"{tid}: missing doc image {s['doc']}")
                out.append(f"![{s['caption']}]({DOC_REL}/{s['doc']})\n\n*{s['caption']}* (`{DOC_REL}/{s['doc']}`, documentation image, not a golden)\n")
                continue
            if not (golden_dir / s["golden"]).is_file():
                errors.append(f"{tid}: missing golden {s['golden']}")
            out.append(f"![{s['caption']}]({GOLDEN_REL}/{s['golden']})\n\n*{s['caption']}* (`{s['golden']}`)\n")
    if none:
        out.append("## Missing screenshots\n\nDone tickets with nothing meaningful to show.\n")
        for tid, title, why in none:
            out.append(f"- **{tid} {title}**: {why}")
        out.append("")
    return "\n".join(out), errors


HEADER = """# UI screenshots of finished tickets

Generated by `tools/screenshots.py` from `screenshots.json`; do not edit by hand. Every image is a committed golden
(640x480, headless Godot, software GL, placeholder art) linked in place from `Unciv.Godot.Harness/golden/`, except entries that say
"documentation image": those are real-GPU pictures under `design/images/` that no scenario run or CI comparison ever reads.

## How screenshots are produced

Each client scenario (`Unciv.Godot.Harness/scenarios.txt`, code in `*Scenario.cs`) drives a seeded game through the real UI,
asserts engine state, then captures a PNG per `Capture` step and compares it with `golden/<scenario>/<step>.png`.
Run inside the `dotnet-dev` container from your worktree (setup: `GODOT.md`):

```
distrobox enter dotnet-dev -- bash -c 'cd <worktree>/csharp/Unciv.Godot.Harness && tools/run-scenario.sh <scenario>'
distrobox enter dotnet-dev -- bash -c 'cd <worktree>/csharp/Unciv.Godot.Harness && tools/run-scenario.sh <scenario> --update-golden'
distrobox enter dotnet-dev -- bash -c 'cd <worktree>/csharp/Unciv.Godot.Harness && tools/run-smoke.sh [--update-golden]'
```

`--update-golden` re-records the PNGs (open them before committing). Fresh frames also land in `out/<scenario>/` (git-ignored).

### Adding a screenshot when you finish a UI ticket

1. Give the ticket a scenario (or extend one) with `Capture` steps and record its goldens with `--update-golden`.
2. Open the PNGs and pick the 1-3 that show the finished feature.
3. Add an entry to `screenshots.json` (ticket id, scenario, `about`, `shots` with golden path and caption). A ticket with
   nothing to show gets `{"none": "reason"}`.
4. Regenerate: `cd csharp/migration && python3 -I tools/screenshots.py` and commit `SCREENSHOTS.md` with the mapping.

`python3 -I tools/screenshots.py --check` fails on a stale page or a missing golden; `ticket.py check` warns about Done
C-track tickets without an entry.
"""


def load_toc():
    spec = importlib.util.spec_from_file_location("toc", Path(__file__).resolve().parent / "toc.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    tool = load_ticket_tool()
    mapping = json.loads(MAPPING.read_text(encoding="utf-8"))
    done = dict(done_c_tickets(tool))
    missing = [t for t in done if t not in mapping]
    if "--missing" in sys.argv:
        print("\n".join(missing))
        return 0
    text, errors = render(mapping, done)
    text = load_toc().add_toc(text)
    errors += [f"{t}: Done C-track ticket has no entry in screenshots.json" for t in missing]
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            errors.append("SCREENSHOTS.md is stale: run python3 -I tools/screenshots.py")
        for e in errors:
            print("ERROR", e)
        return 1 if errors else 0
    for e in errors:
        print("WARN", e, file=sys.stderr)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
