using Unciv.Logic.Map.Tiles;
using Unciv.Models.Ruleset.Tile;
using Unciv.Models.Ruleset.Unique;
using Unciv.Models.StatTypes;
using Unciv.Utils;

namespace Unciv.Logic.City;

// Ported from core/src/com/unciv/logic/city/CityResources.kt (T060). Stripped: the purity annotations.

public static class CityResources
{
    /// <summary>Returns ALL resources, city-wide and civ-wide</summary>
    public static ResourceSupplyList GetResourcesGeneratedByCity(City city)
    {
        var modifiers = GetResourceModifiers(city);
        var cityResources = GetResourcesGeneratedByCityNotIncludingBuildings(city, modifiers);
        cityResources.Add(GetCityResourcesGeneratedFromUniques(city, modifiers, false));
        return cityResources;
    }

    /// <summary>Only for *city-wide* resources - civ-wide resources should use civ-level resources</summary>
    public static ResourceSupplyList GetCityResourcesAvailableToCity(City city)
    {
        var modifiers = GetResourceModifiers(city);

        var cityResources = GetResourcesGeneratedByCityNotIncludingBuildings(city, modifiers);
        // We can't use getResourcesGeneratedByCity directly, because that would include the resources generated by buildings -
        //   which are part of the civ-wide uniques, so we'd be getting them twice!
        // This way we get them once, but it is ugly, I welcome other ideas :/
        cityResources.Add(GetCityResourcesGeneratedFromUniques(city, modifiers, true));

        cityResources.RemoveAll(it => !it.Resource.IsCityWide);

        return cityResources;
    }

    /// <summary>Does not contain any resources for which there is no specific modifier (==1)</summary>
    private static Dictionary<string, float> GetResourceModifiers(City city)
    {
        // Kotlin mutableMapOf() is a LinkedHashMap; ResourceSupplyList.ApplyModifiers only looks entries up by name.
        var modifiers = new Dictionary<string, float>();
        var resources = city.GetRuleset().TileResources.Values;
        city.ForEachMatchingUnique(UniqueType.PercentResourceProduction, unique =>
        {
            var bonus = FloatParse(unique.Params[0]) / 100f;
            foreach (var resource in resources)
            {
                if (resource.MatchesFilter(unique.Params[1], city.State))
                    modifiers[resource.Name] = (modifiers.TryGetValue(resource.Name, out var current) ? current : 1f) + bonus;
            }
        });
        return modifiers;
    }

    private static float FloatParse(string value) =>
        float.Parse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture);

    private static int IntParse(string value) =>
        int.Parse(value, System.Globalization.NumberStyles.AllowLeadingSign, System.Globalization.CultureInfo.InvariantCulture);

    private static ResourceSupplyList GetResourcesGeneratedByCityNotIncludingBuildings(City city, IReadOnlyDictionary<string, float> modifiers)
    {
        var cityResources = new ResourceSupplyList();

        cityResources.Add(GetResourcesFromTiles(city, modifiers));
        cityResources.Add(GetResourceFromUniqueImprovedTiles(city, modifiers));
        cityResources.Add(GetNegativeCityResourcesRequiredByBuildings(city));

        if (city.Civ.IsCityState && city.IsCapital() && city.Civ.CityStateResource != null)
        {
            cityResources.Add(
                city.GetRuleset().TileResources[city.Civ.CityStateResource],
                "Mercantile City-State");
        }

        return cityResources;
    }

    /// <summary>
    /// Gets the number of resources available to this city
    /// Accommodates both city-wide and civ-wide resources
    /// </summary>
    public static int GetAvailableResourceAmount(City city, string resourceName)
    {
        if (!city.GetRuleset().TileResources.TryGetValue(resourceName, out var resource)) return 0;
        return GetAvailableResourceAmount(city, resource);
    }

    /// <summary>
    /// Gets the number of resources available to this city
    /// Accommodates both city-wide and civ-wide resources
    /// </summary>
    public static int GetAvailableResourceAmount(City city, TileResource resource)
    {
        if (!resource.IsCityWide) return city.Civ.GetResourceAmount(resource);
        if (resource.IsStockpiled) return city.ResourceStockpiles[resource.Name];
        return GetCityResourcesAvailableToCity(city).Where(it => it.Resource == resource).Aggregate(0, (sum, it) => unchecked(sum + it.Amount));
    }

    private static ResourceSupplyList GetResourcesFromTiles(City city, IReadOnlyDictionary<string, float> modifiers)
    {
        var resourceSupplyList = new ResourceSupplyList();
        foreach (var tileInfo in city.GetTiles())
        {
            var resource = tileInfo.TileResource;
            if (resource == null) continue;
            var amount = GetTileResourceAmount(city, tileInfo);
            if (amount > 0) resourceSupplyList.Add(resource, "Tiles", amount);
        }
        // Apply the modifiers after adding the totals.
        resourceSupplyList.ApplyModifiers(modifiers);
        return resourceSupplyList;
    }

    private static ResourceSupplyList GetResourceFromUniqueImprovedTiles(City city, IReadOnlyDictionary<string, float> modifiers)
    {
        var resourceSupplyList = new ResourceSupplyList();
        var applicableTiles = city.GetTiles().Where(it => it.GetUnpillagedImprovement() != null).ToList();

        // Calculate how much resource is available.
        foreach (var tileInfo in applicableTiles)
        {
            var gameContext = new GameContext(city.Civ, city, tile: tileInfo);
            var tileImprovement = tileInfo.GetUnpillagedTileImprovement();
            ((IHasUniques)tileImprovement.NotNull()).ForEachMatchingUnique(UniqueType.ProvidesResources, gameContext, unique =>
            {
                if (city.GetRuleset().TileResources.TryGetValue(unique.Params[1], out var resource))
                    resourceSupplyList.Add(
                        resource, "Improvements",
                        IntParse(unique.Params[0]));
            });
        }

        // Apply the resource modifiers.
        resourceSupplyList.ApplyModifiers(modifiers);

        // After resources have been modified, consume them.
        foreach (var tileInfo in applicableTiles)
        {
            var gameContext = new GameContext(city.Civ, city, tile: tileInfo);
            var tileImprovement = tileInfo.GetUnpillagedTileImprovement();
            ((IHasUniques)tileImprovement.NotNull()).ForEachMatchingUnique(UniqueType.ConsumesResources, gameContext, unique =>
            {
                if (city.GetRuleset().TileResources.TryGetValue(unique.Params[1], out var resource))
                    resourceSupplyList.Add(
                        resource, "Improvements",
                        -1 * IntParse(unique.Params[0]));
            });
        }

        return resourceSupplyList;
    }

    private static ResourceSupplyList GetNegativeCityResourcesRequiredByBuildings(City city)
    {
        var resourceSupplyList = new ResourceSupplyList();
        var freeBuildings = city.Civ.CivConstructions.GetFreeBuildingNames(city);
        foreach (var building in city.CityConstructions.GetBuiltBuildings())
        {
            // Free buildings cost no resources
            if (freeBuildings.Contains(building.Name)) continue;
            resourceSupplyList.SubtractResourceRequirements(building.GetResourceRequirementsPerTurn(city.State), city.GetRuleset(), "Buildings");
        }
        return resourceSupplyList;
    }

    private static ResourceSupplyList GetCityResourcesGeneratedFromUniques(City city, IReadOnlyDictionary<string, float> modifiers, bool includeCivUniques = true)
    {
        var buildingResources = new ResourceSupplyList();

        // ProvidesResources - Example: "Provides [1] [Iron]"
        city.ForEachMatchingUnique(UniqueType.ProvidesResources, city.State, includeCivUniques, unique =>
        {
            if (!city.GetRuleset().TileResources.TryGetValue(unique.Params[1], out var resource))
                return;
            buildingResources.Add(
                resource, unique.GetSourceNameForUser(),
                IntParse(unique.Params[0]));
        });

        // StatPercentFromObjectToResource - Example: "[50]% of [Culture] from every [improvementFilter/buildingFilter] in the city added to [Iron]"
        city.ForEachMatchingUnique(UniqueType.StatPercentFromObjectToResource, city.State, includeCivUniques, unique =>
        {
            if (!city.GetRuleset().TileResources.TryGetValue(unique.Params[3], out var resource)) return;
            var stat = StatExtensions.SafeValueOf(unique.Params[1]);
            if (stat == null) return;
            var filter = unique.Params[2];
            double amount = 0.0;

            // Building Filter
            if (UniqueParameterType.BuildingFilter.IsKnownValue(filter, city.GetRuleset()))
            {
                // Kotlin sumOf { Double } accumulates in Double from 0.0, and the sum is then added to amount
                double sum = 0.0;
                foreach (var building in city.CityConstructions.GetBuiltBuildings()
                    .Where(it => it.IsStatRelated(stat.Value) && it.MatchesFilter(filter, city.State)))
                    sum += (double)building.GetStats(city)[stat.Value];
                amount += sum;
            }

            // Improvement Filter
            if (UniqueParameterType.ImprovementFilter.IsKnownValue(filter, city.GetRuleset()))
            {
                double sum = 0.0;
                foreach (var improvement in city.GetWorkedTiles()
                    .Select(it => it.GetUnpillagedTileImprovement())
                    .OfType<TileImprovement>()
                    .Where(it => it[stat.Value] > 0f && it.MatchesFilter(filter, city.State)))
                    sum += (double)improvement[stat.Value];
                amount += sum;
            }

            if (amount > 0.0)
            {
                amount *= DoubleParse(unique.Params[0]) / 100.0;
                buildingResources.Add(resource, unique.GetSourceNameForUser(), KotlinMath.DoubleToInt(amount));
            }
        });

        // After the resources are added, apply the modifiers.
        buildingResources.ApplyModifiers(modifiers);

        return buildingResources;
    }

    private static double DoubleParse(string value) =>
        double.Parse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture);

    private static int GetTileResourceAmount(City city, Tile tile)
    {
        var resource = tile.TileResource;
        if (resource == null) return 0;
        if (!tile.ProvidesResources(city.Civ)) return 0;

        int amountToAdd = resource.ResourceType == ResourceType.Strategic ? tile.ResourceAmount : 1;
        if (resource.ResourceType == ResourceType.Luxury
            && city.ContainsBuildingUnique(UniqueType.ProvidesExtraLuxuryFromCityResources))
            amountToAdd += 1;

        return amountToAdd;
    }
}
