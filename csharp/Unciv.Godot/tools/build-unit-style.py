_cell_cache = {}


def _cell_class(rgb):
    import colorsys
    h, s, v = colorsys.rgb_to_hsv(*[c / 255 for c in rgb])
    if v < 0.25:
        return "dark"
    if s < 0.17:
        return "metal" if v < 0.66 else "cloth"
    if 0.02 <= h <= 0.12 and s < 0.5 and v > 0.74:
        return "skin"
    if 0.02 <= h <= 0.13:
        return "leather"
    return "team"


def cell_classes(folder, body):
    """The palette swatch of every UV cell (8 x 4) of the body's 1024 px texture, read as a surface class. Barbarian keeps the T294 table."""
    if body == "Barbarian":
        return dict(bwo.CELL_CLASS)
    key = BODY_TEX[body]
    if key not in _cell_cache:
        w, h, rows = bwo.read_png(os.path.join(folder, key + "_texture.png"))
        out = {}
        for cy in range(4):
            for cx in range(8):
                px = [0, 0, 0]
                for dy in (0.25, 0.75):
                    for dx in (0.25, 0.75):
                        x, y = int((cx + dx) * w / 8), int((cy + dy) * h / 4)
                        for k in range(3):
                            px[k] += rows[y][x * 3 + k] / 4
                out[(cx, cy)] = _cell_class(px)
        _cell_cache[key] = out
    return _cell_cache[key]


