def _head(c):
    lo, hi = c.head_lo, c.head_hi
    return (lo[0] + hi[0]) / 2, hi[1] - 0.08, (lo[2] + hi[2]) / 2


def hat(c, name, k=1.0, lift=0.0):
    """One of HATS as a surface of revolution on the head. `k` scales it (a rider's head is small against the horse)."""
    mat, brim, crown, h, top = HATS[name][:5]
    cone = len(HATS[name]) > 5
    cx, y0, cz = _head(c)
    y0 += lift
    brim, crown, h, top = brim * k, crown * k, h * k, top * k
    prof = [(brim, y0 - 0.01), (brim * 0.97, y0 + 0.025), (crown * 1.04, y0 + 0.035)]
    if not cone:
        prof.append((crown, y0 + 0.035 + h * 0.8))
    prof += [(top, y0 + 0.035 + h), (0.0, y0 + 0.04 + h)]
    return [lathe(prof, 16, [cx, 0, cz], mat, PAL[mat], c.only("head"))]


