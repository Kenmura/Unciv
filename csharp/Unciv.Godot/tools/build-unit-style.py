    out.append(lathe([(0.0, 0.0), (0.3, 0.1), (0.33, 0.14), (0.0, 0.05)], 14, [0, 0.55, -0.25], "metal", PAL["metal"], JW_NONE, node=node, basis=[[1, 0, 0], [0, 0.6, 0.8], [0, -0.8, 0.6]]))
