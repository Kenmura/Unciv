def _body_bounds(m):
    doc = m.doc
    lo, hi = [1e9] * 3, [-1e9] * 3
    for n in doc["nodes"]:
        if "mesh" in n and "skin" in n:
            for p in doc["meshes"][n["mesh"]]["primitives"]:
                a = doc["accessors"][p["attributes"]["POSITION"]]
                for k in range(3):
                    lo[k], hi[k] = min(lo[k], a["min"][k]), max(hi[k], a["max"][k])
    return lo, hi


LAST = {}  # development: the fit of the last unit built (see build)


def build(folder, body, keep, clips, style_name, seat=None, rider_height=None, height=0.85, look=None):
    """The styled model of one unit as (doc, binary): the same contract as `bum.reduce_body` (one skeleton, six clips, TeamColor, feet at y = 0).

    T310: the figure's scale comes from the proportioned BODY (its height must come out as `height`), never from its gear: a hat, a long gun or a pike must not shrink the unit. The gear is
    built to fit the contract caps (radius 0.62 in the bind pose, total height 0.98); `asset.extras.bodyFit` records the scale actually used over the full-size scale (1.0 = full size) and
    `UnitSilhouetteTests` demands at least 0.97."""
    rider = bool(seat)
    look_name = look
    look = LOOKS.get(style_name, {}).get(look or "", {}) if look else {}
    if look_name and not look and look_name not in LOOKS.get(style_name, {}):
        raise SystemExit(f"unknown look {look_name!r} for style {style_name!r}")
    style = STYLES[style_name](rider, look)
    doc, binary = bum.read_glb(os.path.join(folder, body + ".glb"))
    doc, binary = bum.reduce_body(doc, binary, list(keep), clips, rider_height or 0.7, seat)
    m = bwo.Model(doc, binary)
    rig = next(n for n in m.doc["nodes"] if n.get("name") == "Rig")
    orig_scale = rig.pop("scale")
    newpos, _ = bwo.reproportion(m, **(rider_props(style.prop) if seat else style.prop))
    plain_lo, plain_hi = _body_bounds(m)  # the proportioned body before any gear
    att = style.att
    if seat:  # T308: a rider is drawn at 0.5 of a foot soldier's height, so his gear is oversized to keep the class readable
        att = {k: tuple(v * 1.45 for v in f) if k.endswith(("Shield", "Sword", "Sword_Offhand", "Axe", "Axe_Offhand", "Crossbow")) else f for k, f in att.items()}
    bwo.scale_attachments(m, att)
    ctx = bwo.Ctx(m, newpos)
    style.nodes(ctx, H(m))
    bwo.CELL_CLASS.clear()
    bwo.CELL_CLASS.update(cell_classes(folder, body))
    cfg = dict(drop=style.drop, classify=style.cls, colour=colour)
    prims = bwo.source_prims(m, cfg) + style.extras(ctx)
    for pr in prims:
        if pr.mat == "wood":
            pr.mat = "leather"  # a wood material renders white in Godot 4.7 (T294, cause not found)
    used = {pr.mat for pr in prims}
    if "team" not in used:
        prims += tabard(ctx, width=0.5)
        used.add("team")
    materials = {k: MATS[k] for k in MATS if k in used or k in {pr.mat for pr in prims}}
    bwo.emit(m, prims, materials, 5.0)
    bwo.compact(m)
    lo, hi = bwo.bounds(m)
    if seat:
        rig["scale"] = [x * 0.9 for x in orig_scale]  # the gear (a plume, a hat) adds height: the elephants' riders stay inside the contract
        fit = 1.0
    else:
        full = height / (plain_hi[1] - plain_lo[1])
        radius = max(abs(lo[0]), abs(hi[0]), abs(lo[2]), abs(hi[2]))  # the contract measures the bind pose (arms out, a long gun held sideways): at most 0.62
        scale = min(full, 0.98 / (hi[1] - lo[1]), 0.62 / radius)
        fit = scale / full
        rig["scale"] = [scale] * 3
        rig["translation"] = [0.0, -lo[1] * scale, 0.0]
        LAST.update(fit=fit, radius_fit=0.62 / radius / full, height_fit=0.98 / (hi[1] - lo[1]) / full)
        if os.environ.get("UNCIV_STYLE_DEBUG"):
            print(f"  fit {style_name}/{look_name}: {fit:.3f} (radius {LAST['radius_fit']:.3f}, height {LAST['height_fit']:.3f})", file=sys.stderr)
    m.doc["asset"] = {"version": "2.0", "generator": "build-unit-style.py (T295)", "extras": {"bodyFit": round(fit, 3)}}
    m.doc["buffers"] = [{"byteLength": len(m.bin)}]
    return m.doc, bytes(m.bin)
