"""T295: the owner's chosen gritty look (design/UNIT-STYLE.md, Option 3 "Fur barbarian") for every humanoid and mounted unit, as a layer over `build-unit-models.py`.

`build-unit-models.py` reduces a KayKit body (CC0 1.0, Kay Lousberg) to the six contract clips and calls `style_body(...)` here, which returns the same kind of model (one skeleton, the six
clips, a `TeamColor` material, feet at y = 0) rebuilt with the Option 3 recipe of `build-warrior-options.py` (T294): realistic proportions, skin, leather, fur, iron and cloth surfaces with
their own tiling detail, vertex-colour wear and grime, and generated gear. Only cloth in the civ's colour keeps the `TeamColor` name, so skin, fur and iron are never civ-tinted.

The owner's top priority is that every unit is recognisable at any view, the default play zoom included: a Settler must never be mistaken for an Archer. So the style is not one look
for everybody. Every unit has a `style` in `attachments.json` that fixes its SILHOUETTE (the shape against the grass at the default zoom: head gear, the long held item, the back load, the
lower body), not only its colours:

* axe / sword / spear / bow / javelin / scout / crossbow / musket / rifle / crew: the military classes, each with one long, class-specific item that rises above or sticks out of the body
  (a fur mantle and round shield, a plumed helm and tower shield, a spear taller than the unit, a tall bow and a quiver, a musket and a wide hat, ...);
* settler / worker / great: the civilians. No weapon, a robe or apron down to the ankles (the military have visible legs), a big load (the settler's pack and bedroll, the worker's
  pick and straw hat, a great person's staff, book or sack and a tall headdress).

`tests/.../UnitSilhouetteTests.cs` measures the silhouettes of the built models and fails when two classes look alike.

Nothing here is third-party art besides the KayKit body, mesh and animation library: every added mesh, texture and vertex colour is generated by this script and `build-warrior-options.py`
(original work of this project, MPL-2.0). Stdlib only, deterministic.
"""
