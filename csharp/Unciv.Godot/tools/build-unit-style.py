def _k(rider):
    return 1.55 if rider else 1.0


def _std_extras(c, rider, look, defaults):
    """Hat, back load and body extras of a look, over the style's defaults."""
    get = lambda key: look[key] if key in look else defaults.get(key)
    out = headgear(c, get("hat"), _k(rider))
    for key in ("back", "back2"):
        for name in ([get(key)] if isinstance(get(key), str) else (get(key) or [])):
            out += BACKS[name](c)
    return out


