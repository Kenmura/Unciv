    chest, hips = c.pos["chest"], c.pos["hips"]
    y0, y1 = top if top is not None else chest[1] + 0.16, bottom if bottom is not None else hips[1] - 0.18
    rz = (c.body_hi[2] - c.body_lo[2]) / 2
    cz = (c.body_hi[2] + c.body_lo[2]) / 2
    rx = (c.body_hi[0] - c.body_lo[0]) / 2
    rings = []
    for k in range(5):
        t = k / 4
        pts = []
        for s, z in ((-1, 1), (1, 1), (1, -1), (-1, -1)):
            pts.append([s * rx * width * (1 + 0.2 * t), y0 + (y1 - y0) * t - (0.02 if (k == 4 and s < 0) else 0.0), cz + z * rz * (1.1 + 0.1 * t)])
