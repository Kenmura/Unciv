def robe(c, mat="cloth", flare=1.5, top_mat=None, length_to=0.06):
    """A robe from the waist to the ankles: the civilians' lower outline is one cone, the military's two legs."""
    hips, foot = c.pos["hips"], c.pos["foot.l"]
    y0, y1 = hips[1] + 0.22, foot[1] + length_to
    rx, rz = (c.body_hi[0] - c.body_lo[0]) / 2, (c.body_hi[2] - c.body_lo[2]) / 2
    cz = (c.body_hi[2] + c.body_lo[2]) / 2
    rings = []
    rows = 7
    for k in range(rows):
        t = k / (rows - 1)
        f = 1.0 + (flare - 1.0) * t ** 1.4
        p = ring([0.0, y0 + (y1 - y0) * t, cz], rx * 1.02 * f, rz * 1.18 * f, 18)
        if k == rows - 1:
            for i, q in enumerate(p):
                q[1] += 0.012 * (i % 2)
        rings.append(p)
    return [loft(rings, mat, PAL[mat], lambda p: [(c.ji("hips"), 1.0)] if p[1] < hips[1] + 0.12 else [(c.ji("spine"), 1.0)], close=True, flip=False)]


