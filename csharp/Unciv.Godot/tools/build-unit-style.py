    if kind == "aa":
        return [tube([[0, 0.0, -0.1], [0, 0.55, 0.25], [0, 1.1, 0.5]], [0.07, 0.055, 0.045], 8, "iron", PAL["iron"], JW_NONE, node=node), tube([[0.12, 0.0, -0.1], [0.12, 0.55, 0.25], [0.12, 1.0, 0.45]], [0.04, 0.035, 0.03], 6, "iron", PAL["iron"], JW_NONE, node=node),
                box_prim([0.0, -0.05, -0.1], [0.2, 0.1, 0.2], "iron", PAL["iron"], JW_NONE, node=node)]
    # sam: a box with two raised missile tubes and a dish
    out = [box_prim([0.0, 0.0, 0.0], [0.22, 0.12, 0.3], "iron", PAL["iron"], JW_NONE, node=node)]
