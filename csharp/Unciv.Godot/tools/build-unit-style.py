def _classify(node, cls, cell):
    """Per-node surface class: capes and mantles are fur, the shield face is the civ's cloth, blades are iron, a bare-armed fighter shows skin."""
    if node.endswith("_Cape"):
        return "fur"
    if node.endswith("Shield"):
        return "team" if cell in ((4, 1), (0, 1), (1, 1), (2, 0)) and node != "Spike_Shield" and cls != "metal" else "iron" if cls == "metal" else cls
    if node in ("1H_Axe", "2H_Axe", "1H_Axe_Offhand", "1H_Sword", "2H_Sword", "1H_Sword_Offhand", "Knife", "Knife_Offhand"):
        return "iron" if cls in ("metal", "dark", "team", "cloth") and cell in ((2, 2), (3, 1), (3, 0), (4, 0), (2, 1), (3, 2), (0, 2), (1, 1), (7, 1)) else "leather" if cls == "team" else cls
    if node.endswith("_Hat") or node.endswith("Helmet"):
        return "fur" if node == "Barbarian_Hat" else "iron" if cls in ("metal", "team", "cloth") else cls
    if node in ("Mug", "Spellbook", "1H_Wand", "2H_Staff", "Throwable", "1H_Crossbow", "2H_Crossbow"):
        return "leather" if cls in ("team", "cloth", "skin") else "iron" if cls == "metal" else cls
    return cls


def bare_arms(node, cls, cell):
    """The T294 fix for the skin leak: the body's own blue and white cloth cells never stay TeamColor on bare skin; they are skin, or leather where the body wears clothes."""
    return None


def make_classify(body, bare=True, cloth_team=False):
    """Surface classes for the skinned body. `bare`: the barbarian's chest, arms and shins are skin (T294 option 3); otherwise a body's own clothes become the unit's cloth in the civ's colour only
    where `cloth_team` says so (a tunic), else plain wool: the civ colour is carried by the tabard, shield, crest or sash so it never smears over skin or iron."""
    def classify(node, cls, cell):
        if node.startswith(body + "_") and node.split("_", 1)[1] in ("Body", "ArmLeft", "ArmRight", "LegLeft", "LegRight", "Head", "Head_Hooded"):
            if cls == "team":
                if bare and body == "Barbarian":
                    return "skin"
                return "team" if cloth_team else "wool"
            if cls == "cloth":
                return "wool"
            if cls == "metal" and body != "Knight":
                return "leather"
            return cls
        return _classify(node, cls, cell)
    return classify


